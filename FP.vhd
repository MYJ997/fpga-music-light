library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

ENTITY FP IS
PORT(
    D  : IN  STD_LOGIC_VECTOR(7 DOWNTO 0);
    E  : OUT STD_LOGIC_VECTOR(8 DOWNTO 0);
    CD : OUT STD_LOGIC_VECTOR(9 DOWNTO 0)
);
END FP;

ARCHITECTURE A_FP OF FP IS
BEGIN
    PROCESS(D)
    BEGIN
        CASE D IS
            WHEN "00000000" => E <= "000000000"; CD <= "0000000000";
            WHEN "00000001" => E <= "101111110"; CD <= "0011000000";
            WHEN "00000010" => E <= "101010100"; CD <= "0011100000";
            WHEN "00000011" => E <= "100101111"; CD <= "0011110000";
            WHEN "00000100" => E <= "100011110"; CD <= "0011111000";
            WHEN "00000101" => E <= "111111111"; CD <= "0011111100";
            WHEN "00000110" => E <= "011100011"; CD <= "0011111110";
            WHEN "00000111" => E <= "011001010"; CD <= "0011111111";
            WHEN "00001000" => E <= "010111111"; CD <= "0101000000";
            WHEN "00001001" => E <= "010101010"; CD <= "0101100000";
            WHEN "00001010" => E <= "010010111"; CD <= "0101110000";
            WHEN "00001011" => E <= "010001111"; CD <= "0101111000";
            WHEN "00001100" => E <= "011111111"; CD <= "0101111100";
            WHEN "00001101" => E <= "001110001"; CD <= "0101111110";
            WHEN "00001110" => E <= "001100101"; CD <= "0101111111";
            WHEN "00001111" => E <= "001011111"; CD <= "1001111111";
            WHEN OTHERS     => E <= "000000000"; CD <= "0000000000";
        END CASE;
    END PROCESS;
END A_FP;